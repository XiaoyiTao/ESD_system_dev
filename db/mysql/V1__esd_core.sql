CREATE TABLE IF NOT EXISTS esd_asset_event (
  id BIGINT NOT NULL,
  site_code VARCHAR(32) NOT NULL,
  asset_id BIGINT NOT NULL,
  asset_code VARCHAR(64) NOT NULL,
  event_type VARCHAR(32) NOT NULL,
  before_status TINYINT NULL,
  after_status TINYINT NOT NULL,
  business_record_id BIGINT NULL,
  operator_user_id BIGINT NOT NULL,
  operator_name VARCHAR(100) NULL,
  request_id VARCHAR(64) NULL,
  payload_json JSON NULL,
  event_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_event_asset (site_code, asset_id, event_time),
  KEY idx_event_request (request_id)
) ENGINE=InnoDB COMMENT='ESD 資產不可變事件帳';

CREATE TABLE IF NOT EXISTS esd_import_batch (
  id BIGINT NOT NULL,
  request_id VARCHAR(64) NOT NULL,
  site_code VARCHAR(32) NOT NULL,
  module_code VARCHAR(32) NOT NULL,
  file_name VARCHAR(255) NOT NULL,
  file_sha256 CHAR(64) NOT NULL,
  total_rows INT NOT NULL,
  error_rows INT NOT NULL DEFAULT 0,
