-- ESD System v0.1.0
-- 只建立 ESD 業務資料；平台帳號、密碼、部門、角色和菜單由 platform-system-server 管理。
CREATE DATABASE IF NOT EXISTS platform_esd
  DEFAULT CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE platform_esd;

CREATE TABLE IF NOT EXISTS esd_person_profile (
  id BIGINT NOT NULL,
  site_code VARCHAR(32) NOT NULL,
  platform_user_id BIGINT NOT NULL,
  employee_no VARCHAR(64) NOT NULL,
  employee_name VARCHAR(100) NOT NULL,
  dept_id BIGINT NULL,
  dept_name VARCHAR(100) NULL,
  supervisor_user_id BIGINT NULL,
  supervisor_name VARCHAR(100) NULL,
  floor_code VARCHAR(32) NULL,
  shift_code VARCHAR(32) NULL,
  esd_status TINYINT NOT NULL DEFAULT 1 COMMENT '1 ENABLED, 0 DISABLED',
  creator VARCHAR(64) NULL,
  create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updater VARCHAR(64) NULL,
  update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  deleted BIT NOT NULL DEFAULT b'0',
  active_bind_key VARCHAR(120) GENERATED ALWAYS AS
    (CASE WHEN deleted = b'0' THEN CONCAT(site_code, ':', platform_user_id) ELSE NULL END) STORED,
  PRIMARY KEY (id),
  UNIQUE KEY uk_person_site_user (active_bind_key),
  KEY idx_person_employee (site_code, employee_no),
  KEY idx_person_dept (site_code, dept_id),
  CONSTRAINT ck_person_status CHECK (esd_status IN (0, 1))
) ENGINE=InnoDB COMMENT='ESD 人員擴展檔';

CREATE TABLE IF NOT EXISTS esd_asset (
  id BIGINT NOT NULL,
  asset_code VARCHAR(64) NOT NULL,
  site_code VARCHAR(32) NOT NULL,
  asset_type TINYINT NOT NULL COMMENT '1 GARMENT, 2 SHOES',
  color_code VARCHAR(32) NOT NULL,
  size_code VARCHAR(32) NOT NULL,
  lifecycle_status TINYINT NOT NULL COMMENT '10 AVAILABLE, 20 ISSUED, 30 IN_LAUNDRY, 40 RETIRED, 50 LOST',
  current_holder_user_id BIGINT NULL,
  current_holder_no VARCHAR(64) NULL,
  current_holder_name VARCHAR(100) NULL,
  clean_count INT NOT NULL DEFAULT 0,
  version INT NOT NULL DEFAULT 0,
  creator VARCHAR(64) NULL,
  create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updater VARCHAR(64) NULL,
  update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  deleted BIT NOT NULL DEFAULT b'0',
  PRIMARY KEY (id),
  UNIQUE KEY uk_asset_code (asset_code),
  KEY idx_asset_site_status (site_code, lifecycle_status),
  KEY idx_asset_holder (site_code, current_holder_user_id, asset_type, lifecycle_status),
  CONSTRAINT ck_asset_type CHECK (asset_type IN (1, 2)),
  CONSTRAINT ck_asset_status CHECK (lifecycle_status IN (10, 20, 30, 40, 50)),
  CONSTRAINT ck_asset_clean_count CHECK (clean_count >= 0),
  CONSTRAINT ck_asset_holder CHECK ((lifecycle_status = 20 AND current_holder_user_id IS NOT NULL) OR (lifecycle_status <> 20 AND current_holder_user_id IS NULL))
) ENGINE=InnoDB COMMENT='ESD 資產主檔';

CREATE TABLE IF NOT EXISTS esd_issue_record (
  id BIGINT NOT NULL,
  request_id VARCHAR(64) NOT NULL,
  site_code VARCHAR(32) NOT NULL,
  asset_id BIGINT NOT NULL,
  asset_code VARCHAR(64) NOT NULL,
  asset_type TINYINT NOT NULL,
  employee_user_id BIGINT NOT NULL,
  employee_no VARCHAR(64) NOT NULL,
  employee_name VARCHAR(100) NOT NULL,
  issue_operator_user_id BIGINT NOT NULL,
  issue_operator_name VARCHAR(100) NULL,
  issue_date DATE NOT NULL,
  record_status TINYINT NOT NULL DEFAULT 1 COMMENT '1 ACTIVE, 2 COMPLETED, 3 TERMINATED, 4 REVERSED',
  close_time DATETIME NULL,
  creator VARCHAR(64) NULL,
  create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updater VARCHAR(64) NULL,
  update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  deleted BIT NOT NULL DEFAULT b'0',
  PRIMARY KEY (id),
  UNIQUE KEY uk_issue_request (request_id),
  KEY idx_issue_employee (site_code, employee_user_id, asset_type, record_status),
  KEY idx_issue_asset (site_code, asset_id, record_status)
) ENGINE=InnoDB COMMENT='ESD 發放記錄';

