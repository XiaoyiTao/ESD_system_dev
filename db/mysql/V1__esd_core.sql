CREATE TABLE IF NOT EXISTS esd_alert (
  id BIGINT NOT NULL,
  site_code VARCHAR(32) NOT NULL,
  employee_user_id BIGINT NOT NULL,
  employee_no VARCHAR(64) NOT NULL,
  employee_name VARCHAR(100) NOT NULL,
  alert_type TINYINT NOT NULL COMMENT '1 MULTIPLE_GARMENTS, 2 MULTIPLE_SHOES',
  hold_count INT NOT NULL,
  status TINYINT NOT NULL DEFAULT 1 COMMENT '1 ACTIVE, 2 RESOLVED',
  first_trigger_time DATETIME NOT NULL,
  last_trigger_time DATETIME NOT NULL,
  resolved_time DATETIME NULL,
  description VARCHAR(500) NULL,
  creator VARCHAR(64) NULL,
  create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updater VARCHAR(64) NULL,
  update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  deleted BIT NOT NULL DEFAULT b'0',
