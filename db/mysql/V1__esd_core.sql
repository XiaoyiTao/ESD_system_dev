  file_sha256 CHAR(64) NULL,
  storage_key VARCHAR(500) NULL,
  record_count INT NULL,
  operation_status TINYINT NOT NULL COMMENT '1 STARTED, 2 SUCCESS, 3 FAILED',
  operator_user_id BIGINT NOT NULL,
